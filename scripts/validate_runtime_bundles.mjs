const GRADE_WINDOW_METERS = 100;
const GRADE_BUCKETS = [
  { id: "easy", maxPercent: 5 },
  { id: "moderate", maxPercent: 10 },
  { id: "steep", maxPercent: 15 },
  { id: "verySteep", maxPercent: Number.POSITIVE_INFINITY },
];

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function read(pathname) {
  const raw = fs.readFileSync(pathname, "utf8");
  return { raw, data: JSON.parse(raw) };
}

function readGeneratedModule(pathname) {
  const raw = fs.readFileSync(pathname, "utf8");
  const prefix = "// Generated by scripts/generate_trip_bundles.mjs. Do not hand-edit.\nexport default ";
  const suffix = " as const;\n";
  assert(raw.startsWith(prefix) && raw.endsWith(suffix),
    "flight-status operations module is not in the generated contract format");
  return { raw, data: JSON.parse(raw.slice(prefix.length, -suffix.length)) };
}

function sha256(raw) {
  return crypto.createHash("sha256").update(raw).digest("hex");
}

function approximatelyEqual(first, second, tolerance = 0.000001) {
  return Math.abs(Number(first) - Number(second)) <= tolerance;
}

function validCoordinatePair(value) {
  return (
    Array.isArray(value) &&
    value.length >= 2 &&
    Number.isFinite(Number(value[0])) &&
    Number.isFinite(Number(value[1])) &&
    Math.abs(Number(value[0])) <= 180 &&
    Math.abs(Number(value[1])) <= 90
  );
}

function routePointAtMile(routePath, routeMile) {
  return routePath.find((point) => approximatelyEqual(point[3], routeMile));
}

function round(value, places = 1) {
  const factor = 10 ** places;
  return Math.round(value * factor) / factor;
}

function normalizedElevationAtStation(points, stationMeters) {
  if (stationMeters <= points[0].stationMeters) {
    return Number(points[0].normalizedElevationFeet);
  }
  if (stationMeters >= points.at(-1).stationMeters) {
    return Number(points.at(-1).normalizedElevationFeet);
  }

  let lowerIndex = 0;
  let upperIndex = points.length - 1;
  while (upperIndex - lowerIndex > 1) {
    const middle = Math.floor((lowerIndex + upperIndex) / 2);
    if (points[middle].stationMeters <= stationMeters) lowerIndex = middle;
    else upperIndex = middle;
  }

  const lower = points[lowerIndex];
  const upper = points[upperIndex];
  const fraction =
    (stationMeters - lower.stationMeters) /
    (upper.stationMeters - lower.stationMeters);
  return (
    Number(lower.normalizedElevationFeet) +
    (Number(upper.normalizedElevationFeet) - Number(lower.normalizedElevationFeet)) *
      fraction
  );
}

function gradeBucketFor(absolutePercent) {
  return GRADE_BUCKETS.find((bucket) => absolutePercent < bucket.maxPercent);
}

function buildGradeAnalysis(terrain) {
  const pointForRouteMile = (routeMile) =>
    terrain.points.find(
      (point) => Math.abs(Number(point.routeMile) - Number(routeMile)) < 0.000001,
    );

  return terrain.selectedModel.daily.map((metric) => {
    const start = pointForRouteMile(metric.startRouteMile);
    const finish = pointForRouteMile(metric.endRouteMile);
    assert(start && finish, `Day ${metric.day} is missing a canonical grade boundary`);
    const bucketMeters = Object.fromEntries(GRADE_BUCKETS.map((bucket) => [bucket.id, 0]));
    let maxUphillPercent = 0;
    let maxDownhillPercent = 0;
    let windowCount = 0;
    let stationMeters = start.stationMeters;

    while (stationMeters < finish.stationMeters - 0.001) {
      const nextStationMeters = Math.min(
        stationMeters + GRADE_WINDOW_METERS,
        finish.stationMeters,
      );
      const horizontalMeters = nextStationMeters - stationMeters;
      const gradePercent =
        ((normalizedElevationAtStation(terrain.points, nextStationMeters) -
          normalizedElevationAtStation(terrain.points, stationMeters)) *
          0.3048 *
          100) /
        horizontalMeters;
      const absolutePercent = Math.abs(gradePercent);
      bucketMeters[gradeBucketFor(absolutePercent).id] += horizontalMeters;
      if (gradePercent > 0) maxUphillPercent = Math.max(maxUphillPercent, gradePercent);
      else maxDownhillPercent = Math.max(maxDownhillPercent, absolutePercent);
      windowCount += 1;
      stationMeters = nextStationMeters;
    }

    const totalMeters = Object.values(bucketMeters).reduce((sum, value) => sum + value, 0);
    const maxAbsolutePercent = Math.max(maxUphillPercent, maxDownhillPercent);
    return {
      day: metric.day,
      windowCount,
      maxUphillPercent: round(maxUphillPercent),
      maxDownhillPercent: round(maxDownhillPercent),
      maxAbsolutePercent: round(maxAbsolutePercent),
      maxAbsoluteAngleDegrees: round(
        (Math.atan(maxAbsolutePercent / 100) * 180) / Math.PI,
      ),
      mix: Object.fromEntries(
        GRADE_BUCKETS.map((bucket) => [
          bucket.id,
          {
            meters: round(bucketMeters[bucket.id]),
            percent: round((bucketMeters[bucket.id] / totalMeters) * 100),
          },
        ]),
      ),
    };
  });
}

function validateRuntime(runtime, terrain, terrainHash) {
  const { route = {}, features = [], waterSources = [], driveSegments = [] } = runtime;
  const routePath = route.path;
  const metadata = route.metadata ?? {};
  const properties = route.properties ?? {};
  const selected = terrain.selectedModel;

  assert(Array.isArray(routePath) && routePath.length === terrain.points.length,
    "runtime route path count must equal canonical terrain point count");
  assert(metadata.data_contract_sha256 === terrainHash,
    "runtime data-contract hash does not match canonical terrain artifact");
  assert(runtime.dataContract?.terrainContractSha256 === terrainHash,
    "runtime top-level data-contract hash does not match canonical terrain artifact");
  assert(metadata.active_endpoint === "Ash Camp", "active endpoint must be Ash Camp");
  assert(approximatelyEqual(metadata.active_distance_miles, terrain.route.officialPctaMiles),
    "active route distance must use official PCTA mileage");
  assert(approximatelyEqual(metadata.active_centerline_geometry_miles, terrain.route.extractedCenterlineMiles),
    "runtime must disclose separately measured centerline geometry length");
  assert(!Object.hasOwn(metadata, "active_gps_distance_miles"),
    "legacy Garmin active-distance metadata must not survive in the runtime bundle");
  assert(metadata.geometry_source === terrain.route.geometrySource,
    "runtime geometry provenance is stale");
  assert(metadata.elevation_source === terrain.route.elevationSource,
    "runtime elevation provenance is stale");
  assert(metadata.elevation_accumulation_method === terrain.route.elevationMethod,
    "runtime elevation method is stale");

  assert(properties.total_gain_feet === selected.totalGainFeet,
    "runtime gain must equal canonical selected model");
  assert(properties.total_loss_feet === selected.totalLossFeet,
    "runtime loss must equal canonical selected model");
  assert(properties.min_elevation === selected.minElevationFeet,
    "runtime low point must equal canonical selected model");
  assert(properties.max_elevation === selected.maxElevationFeet,
    "runtime high point must equal canonical selected model");

  let previousRouteMile = -1;
  routePath.forEach((point, index) => {
    assert(
      validCoordinatePair(point) &&
        Number.isFinite(Number(point[2])) &&
        Number.isFinite(Number(point[3])),
      `runtime route point ${index} must be [longitude, latitude, elevationFeet, routeMile]`,
    );
    assert(Number(point[3]) >= previousRouteMile,
      `runtime route mileage regressed at route point ${index}`);
    previousRouteMile = Number(point[3]);
  });
  assert(approximatelyEqual(routePath[0][3], 0), "runtime route must begin at route mile 0");
  assert(approximatelyEqual(routePath.at(-1)[3], terrain.route.officialPctaMiles),
    "runtime route must finish at the official PCTA trip distance");

  const activeFeatures = features
    .filter((feature) => Number(feature?.properties?.day) >= 0)
    .sort((first, second) => first.properties.day - second.properties.day);
  assert(activeFeatures.length === terrain.dayBoundaries.length,
    "runtime must contain Day 0 plus all eight canonical day boundaries");

  terrain.dayBoundaries.forEach((boundary) => {
    const feature = activeFeatures.find(
      (candidate) => Number(candidate.properties?.day) === boundary.day,
    );
    assert(feature, `runtime is missing Day ${boundary.day} boundary feature`);
    assert(validCoordinatePair(feature.geometry?.coordinates),
      `Day ${boundary.day} field feature coordinate is invalid`);
    assert(approximatelyEqual(feature.properties?.routeMile, boundary.routeMile),
      `Day ${boundary.day} route mile drifted from canonical boundary`);
    assert(approximatelyEqual(feature.properties?.pctMile, boundary.pctMile),
      `Day ${boundary.day} PCT mile drifted from canonical boundary`);
    assert(
      validCoordinatePair(feature.properties?.trailCoordinates) &&
        approximatelyEqual(feature.properties.trailCoordinates[0], boundary.trailCoordinates[0]) &&
        approximatelyEqual(feature.properties.trailCoordinates[1], boundary.trailCoordinates[1]),
      `Day ${boundary.day} exact trail coordinate drifted from canonical boundary`,
    );
    assert(
      approximatelyEqual(feature.geometry.coordinates[0], boundary.fieldCoordinates[0]) &&
        approximatelyEqual(feature.geometry.coordinates[1], boundary.fieldCoordinates[1]),
      `Day ${boundary.day} field coordinate drifted from canonical boundary`,
    );
    const routePoint = routePointAtMile(routePath, boundary.routeMile);
    assert(routePoint, `Day ${boundary.day} is not an exact route-path point`);
    assert(
      approximatelyEqual(routePoint[0], boundary.trailCoordinates[0]) &&
        approximatelyEqual(routePoint[1], boundary.trailCoordinates[1]),
      `Day ${boundary.day} route-path coordinate does not match its trail boundary`,
    );
  });

  const day3 = activeFeatures.find((feature) => feature.properties.day === 3);
  assert(
    day3?.properties?.stopType === "support-transfer" &&
      day3?.properties?.packMode === "day-pack-supported" &&
      day3?.properties?.type === "Support Transfer" &&
      Number(day3.properties.fieldToTrailOffsetFeet) === 506,
    "Day 3 must remain an explicit 506-ft-offset supported transfer, not a campsite",
  );
  assert(
    activeFeatures.at(-1)?.properties?.name === "Ash Camp pickup" &&
      activeFeatures.at(-1)?.properties?.type === "Finish",
    "Day 8 must finish at Ash Camp pickup",
  );

  const segments = properties.segments;
  assert(Array.isArray(segments) && segments.length === selected.daily.length,
    "runtime must contain eight canonical day segments");
  selected.daily.forEach((day) => {
    const segment = segments.find((candidate) => Number(candidate.day) === day.day);
    assert(segment, `runtime missing Day ${day.day} segment`);
    [
      ["distance", day.distanceMiles],
      ["routeMileStart", day.startRouteMile],
      ["routeMileEnd", day.endRouteMile],
      ["pctMileStart", day.startPctMile],
      ["pctMileEnd", day.endPctMile],
      ["gain", day.gainFeet],
      ["loss", day.lossFeet],
      ["startElevation", day.startElevationFeet],
      ["endElevation", day.endElevationFeet],
      ["highPoint", day.highPointFeet],
      ["lowPoint", day.lowPointFeet],
    ].forEach(([key, expected]) => {
      assert(approximatelyEqual(segment[key], expected),
        `Day ${day.day} ${key} drifted from canonical terrain`);
    });
  });

  assert(waterSources.length > 0, "runtime water sources must not be empty");
  waterSources.forEach((source, index) => {
    assert(
      validCoordinatePair(source.coordinates) &&
        validCoordinatePair(source.trailCoordinates) &&
        Number.isFinite(Number(source.routeMile)) &&
        Number.isFinite(Number(source.pctMile)) &&
        Number.isFinite(Number(source.trailOffsetFeet)),
      `water source ${index} lacks canonical route projection metadata`,
    );
  });
  assert(waterSources.every((source) => source.reportStatus === "current-condition-check-required"),
    "static water locations must require a current live-condition check");

  const routeRoles = new Set(driveSegments.map((segment) => segment.routeRole));
  assert(routeRoles.has("drive-in") && routeRoles.has("drive-home"),
    "runtime must preserve both Drive In and Drive Home segments");
}

function validateGeneratedFacts(facts, terrain, terrainHash) {
  assert(facts.terrainContractSha256 === terrainHash,
    "web terrain facts hash does not match canonical terrain artifact");
  assert(approximatelyEqual(facts.route.officialPctaMiles, terrain.route.officialPctaMiles),
    "web facts official mileage is stale");
  assert(facts.route.totalGainFeet === terrain.selectedModel.totalGainFeet,
    "web facts total gain is stale");
  assert(facts.route.totalLossFeet === terrain.selectedModel.totalLossFeet,
    "web facts total loss is stale");
  assert(Array.isArray(facts.days) && facts.days.length === terrain.selectedModel.daily.length,
    "web facts day profiles are incomplete");

  assert(facts.schemaVersion >= 2, "web terrain facts must include the generated grade contract");
  assert(facts.route.gradeMethod === facts.gradeAnalysis?.method,
    "web facts grade methodology must remain disclosed");
  assert(facts.gradeAnalysis?.windowMeters === GRADE_WINDOW_METERS,
    "web facts grade window must remain 100m");
  const expectedGrades = buildGradeAnalysis(terrain);
  assert(Array.isArray(facts.gradeAnalysis?.days) &&
    facts.gradeAnalysis.days.length === expectedGrades.length,
  "web terrain grade profiles are incomplete");
  expectedGrades.forEach((expected) => {
    const actual = facts.gradeAnalysis.days.find((candidate) => Number(candidate.day) === expected.day);
    assert(actual, `web facts are missing Day ${expected.day} grade analysis`);
    [
      "windowCount",
      "maxUphillPercent",
      "maxDownhillPercent",
      "maxAbsolutePercent",
      "maxAbsoluteAngleDegrees",
    ].forEach((key) => {
      assert(approximatelyEqual(actual[key], expected[key], 0.1),
        `Day ${expected.day} ${key} does not match canonical normalized terrain`);
    });
    Object.entries(expected.mix).forEach(([bucket, values]) => {
      assert(approximatelyEqual(actual.mix?.[bucket]?.meters, values.meters, 0.1) &&
        approximatelyEqual(actual.mix?.[bucket]?.percent, values.percent, 0.1),
      `Day ${expected.day} ${bucket} grade mix does not match canonical normalized terrain`);
    });
  });
}

function validateRuntimeOperations(operations, source, terrain, terrainHash) {
  assert(operations.terrainContractSha256 === terrainHash,
    "runtime operations terrain contract hash is stale");
  assert(operations.terrainContract === "docs/data/canonical/burney-ash-terrain-2026.json",
    "runtime operations must identify the canonical terrain artifact");
  assert(approximatelyEqual(operations.canonicalRoute?.officialPctaMiles, terrain.route.officialPctaMiles),
    "runtime operations official route distance is stale");
  assert(approximatelyEqual(operations.canonicalRoute?.centerlineGeometryMiles, terrain.route.extractedCenterlineMiles),
    "runtime operations measured centerline distance is stale");
  assert(operations.canonicalRoute?.terrainContractVersion === terrain.contractVersion,
    "runtime operations terrain version is stale");
  assert(operations.canonicalRoute?.dataContractSha256 === terrainHash,
    "runtime operations terrain hash is stale");
  assert(operations.canonicalRoute?.finish?.name === "Ash Camp pickup",
    "runtime operations must use Ash Camp as the finish");
  assert(approximatelyEqual(operations.canonicalRoute?.finish?.routeMile, terrain.route.officialPctaMiles),
    "runtime operations finish route mile is stale");

  const dayThree = terrain.dayBoundaries.find((boundary) => boundary.day === 3);
  assert(operations.dayThreeSupport?.routeMile === dayThree.routeMile,
    "runtime operations Day 3 route mile is stale");
  assert(operations.dayThreeSupport?.pctMile === dayThree.pctMile,
    "runtime operations Day 3 PCT mile is stale");
  assert(operations.dayThreeSupport?.fieldToTrailOffsetFeet === dayThree.fieldToTrailOffsetFeet,
    "runtime operations Day 3 field/trail offset is stale");

  assert(Array.isArray(operations.gates) && operations.gates.length >= 7,
    "runtime operations must preserve every operational gate");
  const gates = new Map(operations.gates.map((gate) => [gate.id, gate]));
  ["united-itinerary", "arrival-night-staging", "burney-day-use", "lake-britton-crossing", "bartle-support", "ash-camp-road", "satellite-comms"].forEach((id) => {
    assert(gates.has(id), `runtime operations is missing the ${id} gate`);
  });
  assert(gates.get("bartle-support")?.state === "open" &&
    gates.get("bartle-support")?.priority === "critical",
  "Bartle support must remain a visible critical open gate");
  assert(gates.get("burney-day-use")?.detail.includes("Saturday"),
    "Burney Saturday reservation constraint must remain explicit");
  assert(operations.workingFlights?.status === "team-confirmed-itinerary",
    "runtime operations must retain the team-confirmed flight itinerary state");
  assert(operations.workingFlights?.inbound?.scheduledDepartureAt === "2026-08-28T18:03:00-07:00" &&
    operations.workingFlights?.outbound?.scheduledArrivalAt === "2026-09-07T10:45:00-07:00",
  "runtime operations must retain the confirmed flight timing contract");
  assert(operations.workingFlights?.flightTracking?.providerState ===
    "official-link-ready-provider-key-pending",
  "runtime operations must disclose the live-flight provider state");
  assert(Array.isArray(operations.workingFlights?.flightTracking?.flights) &&
    operations.workingFlights.flightTracking.flights.length === 2,
  "runtime operations must include both live-flight tracking identities");

  assert(operations.updatedAt === source.updatedAt,
    "runtime operations freshness must come from the canonical operations file");
  assert(operations.sources?.length === source.sources?.length,
    "runtime operations sources must remain aligned with the canonical operations file");
}

function validateRuntimeFieldBrief(brief, source, operations, terrain, terrainHash) {
  assert(brief.terrainContractSha256 === terrainHash,
    "field brief terrain contract hash is stale");
  assert(brief.terrainContractVersion === terrain.contractVersion,
    "field brief terrain contract version is stale");
  assert(approximatelyEqual(brief.route?.officialPctaMiles, terrain.route.officialPctaMiles),
    "field brief official mileage is stale");
  assert(approximatelyEqual(brief.route?.centerlineGeometryMiles, terrain.route.extractedCenterlineMiles),
    "field brief centerline mileage is stale");
  assert(brief.route?.totalGainFeet === terrain.selectedModel.totalGainFeet,
    "field brief gain is stale");
  assert(brief.route?.totalLossFeet === terrain.selectedModel.totalLossFeet,
    "field brief loss is stale");
  assert(brief.updatedAt === source.updatedAt,
    "field brief updatedAt must come from its canonical source");
  assert(Array.isArray(brief.daily) && brief.daily.length === terrain.selectedModel.daily.length,
    "field brief must include all eight generated hiking days");

  terrain.selectedModel.daily.forEach((metric) => {
    const day = brief.daily.find((candidate) => Number(candidate.day) === metric.day);
    assert(day, `field brief is missing Day ${metric.day}`);
    [
      ["distanceMiles", metric.distanceMiles],
      ["gainFeet", metric.gainFeet],
      ["lossFeet", metric.lossFeet],
      ["routeMileStart", metric.startRouteMile],
      ["routeMileEnd", metric.endRouteMile],
      ["pctMileStart", metric.startPctMile],
      ["pctMileEnd", metric.endPctMile],
    ].forEach(([key, expected]) => {
      assert(approximatelyEqual(day[key], expected),
        `field brief Day ${metric.day} ${key} drifted from canonical terrain`);
    });
  });

  assert(brief.operations?.dayThreeSupport?.fieldToTrailOffsetFeet === 506,
    "field brief must keep Day 3's 506-ft field/trail distinction");
  assert(brief.operations?.finishPlan?.routeMile === terrain.route.officialPctaMiles,
    "field brief finish must remain Ash Camp at the official trip mile");
  assert(Array.isArray(brief.operations?.gates) && brief.operations.gates.length === operations.gates.length,
    "field brief must carry every operational gate");
  assert(Array.isArray(brief.emergency?.contacts) && brief.emergency.contacts.length >= 5,
    "field brief must include its verified emergency contacts");

  const sourceIDs = new Set((brief.sources ?? []).map((item) => item.id));
  const referenced = new Set([
    ...(brief.sourceIds ?? []),
    ...((brief.emergency?.contacts ?? []).flatMap((contact) => contact.sourceIds ?? [])),
  ]);
  assert(sourceIDs.size === referenced.size && [...referenced].every((id) => sourceIDs.has(id)),
    "field brief source links must resolve from the operations source registry");
}

function main() {
  const { raw: terrainRaw, data: terrain } = read(terrainPath);
  const terrainHash = sha256(terrainRaw);
  const facts = read(factsPath).data;
  const operationsSource = read(operationsSourcePath).data;
  const operationsWeb = read(operationsRuntimePaths.web);
  const operationsIOS = read(operationsRuntimePaths.ios);
  const operationsFlightStatus = read(operationsRuntimePaths.flightStatus);
  const operationsFlightStatusModule = readGeneratedModule(flightStatusOperationsModulePath);
  const fieldBriefSource = read(fieldBriefSourcePath).data;
  const fieldBriefWeb = read(fieldBriefRuntimePaths.web);
  const fieldBriefPublic = read(fieldBriefRuntimePaths.public);
  const fieldBriefIOS = read(fieldBriefRuntimePaths.ios);
  const web = read(runtimePaths.web);
  const ios = read(runtimePaths.ios);

  assert(web.raw === ios.raw,
    "web and iOS hike_data.json bundles differ; regenerate instead of hand-editing either copy");
  if (fs.existsSync(runtimePaths.localMirror)) {
    assert(read(runtimePaths.localMirror).raw === web.raw,
      "local web source mirror differs from the generated runtime bundle");
  }
  assert(operationsWeb.raw === operationsIOS.raw && operationsWeb.raw === operationsFlightStatus.raw,
    "web, iOS, and flight-status operational bundles differ; regenerate instead of hand-editing any copy");
  assert(JSON.stringify(operationsFlightStatusModule.data) === JSON.stringify(operationsWeb.data),
    "flight-status TypeScript module differs from the generated operational bundle");
  assert(fieldBriefWeb.raw === fieldBriefPublic.raw && fieldBriefWeb.raw === fieldBriefIOS.raw,
    "web public, web bundled, and iOS field briefs differ; regenerate instead of hand-editing any copy");
  assert(fs.existsSync(fieldBriefMarkdownPath),
    "generated markdown field brief is missing; run data:generate");
  assert(fs.existsSync(fieldBriefPublicMarkdownPath),
    "public markdown field brief is missing; run data:generate");
  assert(
    fs.readFileSync(fieldBriefMarkdownPath, "utf8") ===
      fs.readFileSync(fieldBriefPublicMarkdownPath, "utf8"),
    "document and public markdown field briefs differ; regenerate instead of hand-editing either copy",
  );

  validateRuntime(web.data, terrain, terrainHash);
  validateGeneratedFacts(facts, terrain, terrainHash);
  validateRuntimeOperations(operationsWeb.data, operationsSource, terrain, terrainHash);
  validateRuntimeOperations(operationsFlightStatus.data, operationsSource, terrain, terrainHash);
  validateRuntimeOperations(operationsFlightStatusModule.data, operationsSource, terrain, terrainHash);
  validateRuntimeFieldBrief(
    fieldBriefWeb.data,
    fieldBriefSource,
    operationsWeb.data,
    terrain,
    terrainHash,
  );

  console.log("✓ Runtime bundles exactly match the canonical PCTA + USGS terrain contract");
  console.table({
    "Runtime points": web.data.route.path.length,
    "Official PCTA miles": terrain.route.officialPctaMiles,
    "Normalized gain ft": terrain.selectedModel.totalGainFeet,
    "Normalized loss ft": terrain.selectedModel.totalLossFeet,
    "Water sources": web.data.waterSources.length,
    "Web/iOS bundles": "byte-identical",
    "Operational gates": operationsWeb.data.gates.length,
    "Field brief contacts": fieldBriefWeb.data.emergency.contacts.length,
  });
}

try {
  main();
} catch (error) {
  console.error(`Runtime bundle validation failed: ${error.message}`);
  process.exitCode = 1;
}
